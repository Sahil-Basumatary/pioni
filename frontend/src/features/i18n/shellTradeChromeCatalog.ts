export function tradeChromeMessage(
  language: AppLanguage,
  key: TradeChromeMessageKey,
  vars?: Record<string, string>,
): string {
  const table = TRADE_CHROME_CATALOG[language] ?? enUS;
  let value = table[key] ?? enUS[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(replacement);
    }
  }
  return value;
}
